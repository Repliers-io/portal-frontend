import { readFileSync, writeFileSync } from 'fs'
import { resolve } from 'path'
import { fileURLToPath } from 'url'

const scriptsDir = resolve(fileURLToPath(import.meta.url), '..')
const d = JSON.parse(
  readFileSync(resolve(scriptsDir, '../../../gta-areas-merged.json'), 'utf8')
)
const coords = JSON.stringify(d.searchPolygon, null, 2)

// The merged region names, wrapped into comment lines, so the generated config
// says which locations it was built from.
const sources = (d.names ?? [])
  .join(', ')
  .split(' ')
  .reduce((lines, word) => {
    const last = lines[lines.length - 1]
    if (last && `${last} ${word}`.length <= 74)
      lines[lines.length - 1] = `${last} ${word}`
    else lines.push(word)
    return lines
  }, [])
  .map((line) => `// ${line}`)
  .join('\n')

// bounds ring: [SW, NW, NE, SE, SW]
const [[swLng, swLat], , [neLng, neLat]] = d.bounds

const content = `// Auto-generated by gen-search-boundary.js — do not edit manually
import type { Position } from 'geojson'

// Buffered + simplified search boundary polygon, the union of:
${sources}
// Used to constrain all listing queries to the covered region.
// Position[][][] = array of polygons, each polygon = array of rings.
export const gtaSearchBoundary: Position[][][] = ${coords}

// Bounding box of the search boundary, used as defaultPolygon fallback.
export const gtaBounds = [
  { lat: ${neLat}, lng: ${swLng} },
  { lat: ${neLat}, lng: ${neLng} },
  { lat: ${swLat}, lng: ${neLng} },
  { lat: ${swLat}, lng: ${swLng} }
]
`
const out = resolve(
  scriptsDir,
  '../src/configs/movesmartly-com/searchBoundary.ts'
)
writeFileSync(out, content)
console.log('Written:', out)
